const DICTS: Record<Lang, Partial<Record<TKey, string>>> = { en, am, om };
const STORAGE_KEY = 'lang';

type Vars = Record<string, string | number>;
type Ctx = { lang: Lang; locale: string; setLang: (l: Lang) => void; t: (key: TKey, vars?: Vars) => string };

const fill = (s: string, vars?: Vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s);

const I18nContext = createContext<Ctx>({ lang: 'en', locale: 'en-GB', setLang: () => {}, t: (k, v) => fill(en[k], v) });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && saved in DICTS) setLangState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem(STORAGE_KEY, l);
  }, []);
  const t = useCallback((key: TKey, vars?: Vars) => fill(DICTS[lang][key] ?? en[key] ?? key, vars), [lang]);
  const locale = LANGUAGES.find((l) => l.code === lang)!.locale;

  return <I18nContext.Provider value={{ lang, locale, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
export const useT = () => useContext(I18nContext).t;
